export const allInstruments: Stock[] = [...indices, ...stocks];

export function getStockById(id: string): Stock | undefined {
  return allInstruments.find((item) => item.id === id);
}

export function getStock(market: string, symbol: string): Stock | undefined {
  const key = symbol.toUpperCase();
  return allInstruments.find(
    (item) => item.market === market && item.symbol.toUpperCase() === key,
  );
}

export function stocksByMarket(market: "us" | "tw"): Stock[] {
  return stocks.filter((item) => item.market === market);
}

export function searchStocks(query: string, limit = 8): Stock[] {
  const q = query.trim().toLowerCase();
  if (!q) return [];
  return stocks
    .filter((item) => {
      return (
        item.symbol.toLowerCase().includes(q) ||
        item.nameZh.toLowerCase().includes(q) ||
        item.nameEn.toLowerCase().includes(q)
      );
    })
    .slice(0, limit);
}
